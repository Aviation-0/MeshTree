//! Handoff records, `HANDOFF.md`, and the generated `AGENTS.md` block.
//!
//! Authoritative specification: `SPEC.md` §2 (G5), §13 (per-task handoff on
//! the task branch; a deterministic, bounded "Active Sessions" block in the
//! root `AGENTS.md`, ordered by task id, capped at 10 lines by default),
//! §18 (byte-stable snapshots).
//!
//! Everything here is pure: the same inputs always render the same bytes, so
//! git diffs and prompt caches stay stable. Agent-written text is flattened
//! to one line per item and HTML-comment delimiters are defused, so no field
//! can forge or break the block markers.

use crate::task::{Task, TaskId};
use serde::{Deserialize, Serialize};

/// First line of the generated block.
pub const BEGIN_MARKER: &str = "<!-- meshtree:active-sessions begin -->";
/// Last line of the generated block.
pub const END_MARKER: &str = "<!-- meshtree:active-sessions end -->";
/// Second line of the generated block.
pub const GENERATED_NOTE: &str = "<!-- Generated by MeshTree. Do not edit between markers. -->";
/// Heading inside the block.
pub const HEADING: &str = "## Active Sessions";
/// Default cap on session lines in the block (`SPEC.md` §13).
pub const DEFAULT_LINE_CAP: usize = 10;

/// A design decision and its reason.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Decision {
    pub what: String,
    pub why: String,
}

/// `handoff.json` (`SPEC.md` §13). Every field is optional on input.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct HandoffRecord {
    #[serde(default)]
    pub objective: String,
    #[serde(default)]
    pub state: String,
    #[serde(default)]
    pub done: Vec<String>,
    #[serde(default)]
    pub next: Vec<String>,
    #[serde(default)]
    pub failing_tests: Vec<String>,
    #[serde(default)]
    pub decisions: Vec<Decision>,
    #[serde(default)]
    pub ruled_out: Vec<String>,
}

impl HandoffRecord {
    /// Canonical `handoff.json` bytes: pretty-printed in field order, LF line
    /// endings, trailing newline.
    pub fn to_json(&self) -> String {
        let mut json = serde_json::to_string_pretty(self).expect("HandoffRecord serializes");
        json.push('\n');
        json
    }
}

/// One active task as listed in the `AGENTS.md` block.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ActiveSession {
    pub id: TaskId,
    pub name: String,
    pub agent: Option<String>,
    pub machine: String,
    /// The task's handoff, if it has committed one.
    pub handoff: Option<HandoffRecord>,
}

impl ActiveSession {
    /// The session for `task` with its handoff (if any).
    pub fn from_task(task: &Task, handoff: Option<HandoffRecord>) -> Self {
        Self {
            id: task.id.clone(),
            name: task.name.clone(),
            agent: task.agent.clone(),
            machine: task.machine.clone(),
            handoff,
        }
    }
}

/// One line of agent-written text: whitespace runs (including newlines)
/// collapsed to single spaces, and `<!--` / `-->` defused.
pub fn clean(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace("<!--", "<!\u{2010}-")
        .replace("-->", "-\u{2010}>")
}

/// `text` with one terminal period.
fn sentence(text: &str) -> String {
    let text = clean(text);
    if text.ends_with(['.', '!', '?']) {
        text
    } else {
        format!("{text}.")
    }
}

/// Renders `HANDOFF.md` for `task` (§13). Empty fields and lists are omitted.
pub fn render_handoff_md(id: &TaskId, name: &str, record: &HandoffRecord) -> String {
    let mut out = format!("# Handoff: {} ({id})\n", clean(name));
    let mut field = |label: &str, value: &str| {
        if !value.trim().is_empty() {
            out.push_str(&format!("\n**{label}:** {}\n", clean(value)));
        }
    };
    field("Objective", &record.objective);
    field("State", &record.state);
    let mut list = |title: &str, items: Vec<String>| {
        if !items.is_empty() {
            out.push_str(&format!("\n## {title}\n\n"));
            for item in items {
                out.push_str(&format!("- {item}\n"));
            }
        }
    };
    let plain = |v: &[String]| v.iter().map(|s| clean(s)).collect::<Vec<_>>();
    list("Done", plain(&record.done));
    list("Next", plain(&record.next));
    list(
        "Failing tests",
        record
            .failing_tests
            .iter()
            .map(|t| format!("`{}`", clean(t).replace('`', "'")))
            .collect(),
    );
    list(
        "Decisions",
        record
            .decisions
            .iter()
            .map(|d| format!("{} (why: {})", clean(&d.what), clean(&d.why)))
            .collect(),
    );
    list("Ruled out", plain(&record.ruled_out));
    out
}

/// The lines describing one session (one or two).
fn session_lines(session: &ActiveSession) -> Vec<String> {
    let who = match &session.agent {
        Some(agent) => format!("{}, {}", clean(agent), clean(&session.machine)),
        None => clean(&session.machine),
    };
    let handoff = session.handoff.clone().unwrap_or_default();
    let state = if handoff.state.trim().is_empty() {
        "active.".to_string()
    } else {
        sentence(&handoff.state)
    };
    let mut lines = vec![format!(
        "- [{}] {} ({who}): {state}",
        session.id,
        clean(&session.name)
    )];
    let mut detail = Vec::new();
    if let Some(next) = handoff.next.iter().find(|n| !n.trim().is_empty()) {
        detail.push(format!("Next: {}", sentence(next)));
    }
    let failing: Vec<String> = handoff
        .failing_tests
        .iter()
        .map(|t| clean(t))
        .filter(|t| !t.is_empty())
        .collect();
    if !failing.is_empty() {
        detail.push(format!("Failing: {}", sentence(&failing.join(", "))));
    }
    if !detail.is_empty() {
        lines.push(format!("  {}", detail.join(" ")));
    }
    lines
}

/// Renders the `AGENTS.md` block (markers included, LF line endings,
/// trailing newline). Sessions are ordered by task id. At most `cap` session
/// lines are emitted; when sessions are left out, whole entries are dropped
/// from the end and the last line says how many (`cap` ≥ 1).
pub fn render_agents_block(sessions: &[ActiveSession], cap: usize) -> String {
    let cap = cap.max(1);
    let mut sorted: Vec<&ActiveSession> = sessions.iter().collect();
    sorted.sort_by(|a, b| a.id.cmp(&b.id));
    let entries: Vec<Vec<String>> = sorted.iter().map(|s| session_lines(s)).collect();

    let mut body: Vec<String> = Vec::new();
    if entries.is_empty() {
        body.push("- (none)".to_string());
    } else if entries.iter().map(Vec::len).sum::<usize>() <= cap {
        body.extend(entries.into_iter().flatten());
    } else {
        // Keep whole entries within cap - 1 lines, then a summary line.
        let mut shown = 0;
        for entry in &entries {
            if body.len() + entry.len() > cap - 1 {
                break;
            }
            body.extend(entry.iter().cloned());
            shown += 1;
        }
        let more = entries.len() - shown;
        body.push(format!(
            "- … and {more} more active session{} (`meshtree status`).",
            if more == 1 { "" } else { "s" }
        ));
    }

    let mut out = String::new();
    for line in [BEGIN_MARKER, GENERATED_NOTE, HEADING]
        .into_iter()
        .map(str::to_string)
        .chain(body)
        .chain([END_MARKER.to_string()])
    {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Puts `block` (from [`render_agents_block`]) into `agents_md`:
///
/// - between existing markers (the old block, markers included, is replaced);
/// - else in place of a trailing, empty `## Active Sessions` heading;
/// - else appended after a blank line.
///
/// The file's line ending (CRLF if it uses any) is applied to the block.
/// Idempotent: splicing the same block twice equals splicing it once.
pub fn splice_agents_md(agents_md: &str, block: &str) -> String {
    let crlf = agents_md.contains("\r\n");
    let block = if crlf {
        block.replace("\r\n", "\n").replace('\n', "\r\n")
    } else {
        block.to_string()
    };
    let nl = if crlf { "\r\n" } else { "\n" };

    if let (Some(begin), Some(end)) = (agents_md.find(BEGIN_MARKER), agents_md.find(END_MARKER)) {
        if begin < end {
            let mut after = end + END_MARKER.len();
            if agents_md[after..].starts_with(nl) {
                after += nl.len();
            }
            return format!("{}{block}{}", &agents_md[..begin], &agents_md[after..]);
        }
    }

    let trimmed = agents_md.trim_end();
    if let Some(head) = trimmed.strip_suffix(HEADING) {
        if head.is_empty() || head.ends_with('\n') {
            return format!("{head}{block}");
        }
    }

    if trimmed.is_empty() {
        return block;
    }
    format!("{trimmed}{nl}{nl}{block}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn clean_flattens_and_defuses_markers() {
        assert_eq!(clean("  a\n b\t\tc  "), "a b c");
        let forged = format!("x {END_MARKER} y");
        let cleaned = clean(&forged);
        assert!(!cleaned.contains("-->"), "{cleaned}");
        assert!(!cleaned.contains("<!--"), "{cleaned}");
    }

    #[test]
    fn sentence_adds_one_period() {
        assert_eq!(sentence("done"), "done.");
        assert_eq!(sentence("done."), "done.");
        assert_eq!(sentence("why?"), "why?");
    }

    #[test]
    fn handoff_json_roundtrip_with_defaults() {
        let partial: HandoffRecord = serde_json::from_str(r#"{"state":"x"}"#).unwrap();
        assert_eq!(partial.state, "x");
        assert!(partial.next.is_empty() && partial.objective.is_empty());
        let back: HandoffRecord = serde_json::from_str(&partial.to_json()).unwrap();
        assert_eq!(back, partial);
        assert!(partial.to_json().ends_with("}\n"));
    }
}
