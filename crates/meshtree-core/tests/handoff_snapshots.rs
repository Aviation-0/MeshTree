//! Byte-stable `HANDOFF.md` and `AGENTS.md` rendering (`SPEC.md` §13, §18
//! "Handoff → AGENTS.md rendering: byte-stable snapshots").

use meshtree_core::handoff::{
    render_agents_block, render_handoff_md, splice_agents_md, ActiveSession, Decision,
    HandoffRecord, DEFAULT_LINE_CAP, END_MARKER,
};
use meshtree_core::TaskId;

const ID1: &str = "t-00000000000000000000000001";
const ID2: &str = "t-00000000000000000000000002";
const ID3: &str = "t-00000000000000000000000003";

fn id(s: &str) -> TaskId {
    TaskId::parse(s).expect("valid task id literal")
}

/// The `SPEC.md` §13 example record.
fn spec_example() -> HandoffRecord {
    HandoffRecord {
        objective: "Add idempotency checks to Stripe webhook handler".into(),
        state: "mid-implementation".into(),
        done: vec![
            "idempotency-key column added".into(),
            "migrations written".into(),
        ],
        next: vec![
            "wrap handler in transaction".into(),
            "write replay test".into(),
        ],
        failing_tests: vec!["webhooks::test_double_charge".into()],
        decisions: vec![Decision {
            what: "use upsert instead of lock".into(),
            why: "avoids row lock contention".into(),
        }],
        ruled_out: vec!["redis-based dedupe — rejected as non-local-first".into()],
    }
}

fn sessions() -> Vec<ActiveSession> {
    vec![
        ActiveSession {
            id: id(ID2),
            name: "fix-auth-middleware".into(),
            agent: Some("vibe-cli".into()),
            machine: "mc-lucas-win".into(),
            handoff: Some(spec_example()),
        },
        ActiveSession {
            id: id(ID3),
            name: "evil\nname".into(),
            agent: Some("antigravity".into()),
            machine: "mc-x".into(),
            handoff: Some(HandoffRecord {
                state: "done-ish.".into(),
                failing_tests: vec!["a".into(), "b".into()],
                ..HandoffRecord::default()
            }),
        },
        ActiveSession {
            id: id(ID1),
            name: "docs".into(),
            agent: None,
            machine: "mc-lucas-mac".into(),
            handoff: None,
        },
    ]
}

const HANDOFF_MD: &str = "# Handoff: fix-auth-middleware (t-00000000000000000000000002)

**Objective:** Add idempotency checks to Stripe webhook handler

**State:** mid-implementation

## Done

- idempotency-key column added
- migrations written

## Next

- wrap handler in transaction
- write replay test

## Failing tests

- `webhooks::test_double_charge`

## Decisions

- use upsert instead of lock (why: avoids row lock contention)

## Ruled out

- redis-based dedupe — rejected as non-local-first
";

const BLOCK: &str = "<!-- meshtree:active-sessions begin -->
<!-- Generated by MeshTree. Do not edit between markers. -->
## Active Sessions
- [t-00000000000000000000000001] docs (mc-lucas-mac): active.
- [t-00000000000000000000000002] fix-auth-middleware (vibe-cli, mc-lucas-win): mid-implementation.
  Next: wrap handler in transaction. Failing: webhooks::test_double_charge.
- [t-00000000000000000000000003] evil name (antigravity, mc-x): done-ish.
  Failing: a, b.
<!-- meshtree:active-sessions end -->
";

const BLOCK_CAP_3: &str = "<!-- meshtree:active-sessions begin -->
<!-- Generated by MeshTree. Do not edit between markers. -->
## Active Sessions
- [t-00000000000000000000000001] docs (mc-lucas-mac): active.
- … and 2 more active sessions (`meshtree status`).
<!-- meshtree:active-sessions end -->
";

const EMPTY_BLOCK: &str = "<!-- meshtree:active-sessions begin -->
<!-- Generated by MeshTree. Do not edit between markers. -->
## Active Sessions
- (none)
<!-- meshtree:active-sessions end -->
";

#[test]
fn handoff_and_agents_md_byte_stable_snapshots() {
    // HANDOFF.md for the §13 example; handoff.json round-trips.
    let record = spec_example();
    assert_eq!(
        render_handoff_md(&id(ID2), "fix-auth-middleware", &record),
        HANDOFF_MD
    );
    let json = record.to_json();
    assert_eq!(
        serde_json::from_str::<HandoffRecord>(&json).unwrap(),
        record
    );
    assert_eq!(spec_example().to_json(), json, "deterministic bytes");
    // Empty sections are omitted.
    assert_eq!(
        render_handoff_md(&id(ID1), "docs", &HandoffRecord::default()),
        format!("# Handoff: docs ({ID1})\n")
    );

    // The block: sorted by task id whatever the input order, LF, stable.
    let mut input = sessions();
    assert_eq!(render_agents_block(&input, DEFAULT_LINE_CAP), BLOCK);
    input.reverse();
    assert_eq!(render_agents_block(&input, DEFAULT_LINE_CAP), BLOCK);
    input.swap(0, 1);
    assert_eq!(render_agents_block(&input, DEFAULT_LINE_CAP), BLOCK);

    // Capped: whole entries, then a count of the rest.
    assert_eq!(render_agents_block(&input, 3), BLOCK_CAP_3);
    assert_eq!(render_agents_block(&[], DEFAULT_LINE_CAP), EMPTY_BLOCK);
    let many: Vec<ActiveSession> = (1..=30u128)
        .map(|n| ActiveSession {
            id: TaskId::from_ulid(n),
            name: format!("task-{n}"),
            agent: None,
            machine: "mc".into(),
            handoff: None,
        })
        .collect();
    let capped = render_agents_block(&many, DEFAULT_LINE_CAP);
    let body = capped.lines().count() - 4; // markers, note, heading
    assert_eq!(body, DEFAULT_LINE_CAP);
    assert!(
        capped.contains("- … and 21 more active sessions"),
        "{capped}"
    );

    // Agent text cannot forge the end marker.
    let forged = vec![ActiveSession {
        id: id(ID1),
        name: format!("x {END_MARKER}"),
        agent: None,
        machine: "mc".into(),
        handoff: Some(HandoffRecord {
            state: format!("{END_MARKER}\n# injected"),
            ..HandoffRecord::default()
        }),
    }];
    let block = render_agents_block(&forged, DEFAULT_LINE_CAP);
    assert_eq!(block.matches(END_MARKER).count(), 1, "{block}");
    assert_eq!(block.lines().count(), 5, "no injected lines: {block}");

    // Splicing into AGENTS.md.
    let doc = "# Project\n\nIntro.\n";
    let once = splice_agents_md(doc, BLOCK);
    assert_eq!(once, format!("# Project\n\nIntro.\n\n{BLOCK}"));
    assert_eq!(splice_agents_md(&once, BLOCK), once, "idempotent");
    assert_eq!(
        splice_agents_md(&once, EMPTY_BLOCK),
        format!("# Project\n\nIntro.\n\n{EMPTY_BLOCK}"),
        "the old block is replaced"
    );
    // Markers mid-file: content before and after is preserved byte for byte.
    let middle = format!("A\n\n{EMPTY_BLOCK}\n## Later\nB\n");
    assert_eq!(
        splice_agents_md(&middle, BLOCK),
        format!("A\n\n{BLOCK}\n## Later\nB\n")
    );
    // A trailing, empty `## Active Sessions` heading is adopted.
    assert_eq!(
        splice_agents_md("# Contract\n\n## Active Sessions\n", BLOCK),
        format!("# Contract\n\n{BLOCK}")
    );
    assert_eq!(splice_agents_md("", BLOCK), BLOCK);
    // CRLF files stay CRLF.
    let crlf = splice_agents_md("# P\r\n", BLOCK);
    assert_eq!(crlf, format!("# P\r\n\r\n{}", BLOCK.replace('\n', "\r\n")));
    assert!(!crlf.replace("\r\n", "").contains('\n'));
    assert_eq!(splice_agents_md(&crlf, BLOCK), crlf);
}
