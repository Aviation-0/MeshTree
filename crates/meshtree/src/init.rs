//! `meshtree init`: write the `.meshtree/config.toml` template and initialize `.meshtree/`.
//!
//! Authoritative specification: `SPEC.md` §5 (on-disk layout), §6 (config),
//! §14 (CLI, exit codes), §16 (`MT-050`).
//!
//! Idempotent: existing files are never overwritten. A pre-existing
//! `config.toml` is validated and reported with `MT-050` if invalid.

use crate::exit::{CliError, PLATFORM, USAGE};
use meshtree_core::Config;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Directory holding all MeshTree state inside the repository.
pub const MESHTREE_DIR: &str = ".meshtree";

/// Subdirectories created under `.meshtree/` (`SPEC.md` §5).
pub const SUBDIRS: [&str; 3] = ["worktrees", "tasks", "quarantine"];

/// `.meshtree/.gitignore`: everything is machine-local except the committed
/// config (§6) and per-task handoff records, which live on task branches (§13).
pub const GITIGNORE: &str =
    "# Generated by `meshtree init` (SPEC.md §5). Machine-local state is ignored.
*
!.gitignore
!config.toml
!tasks/
!tasks/*/
!tasks/*/HANDOFF.md
!tasks/*/handoff.json
";

/// What `init` did to each managed file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileOutcome {
    /// File was written.
    Created,
    /// File already existed and was left untouched.
    Kept,
}

/// Summary of an `init` run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitReport {
    /// Repository root containing `.meshtree/`.
    pub repo_root: PathBuf,
    /// Outcome for `.meshtree/config.toml`.
    pub config: FileOutcome,
    /// Outcome for `.meshtree/.gitignore`.
    pub gitignore: FileOutcome,
}

/// Finds the repository root: the nearest ancestor of `start` containing `.git`
/// (a directory, or a file for linked worktrees and submodules).
pub fn find_repo_root(start: &Path) -> Option<PathBuf> {
    start
        .ancestors()
        .find(|dir| dir.join(".git").exists())
        .map(Path::to_path_buf)
}

/// Runs `meshtree init` from working directory `cwd`.
pub fn run(cwd: &Path) -> Result<InitReport, CliError> {
    let repo_root = find_repo_root(cwd).ok_or_else(|| {
        CliError::new(
            USAGE,
            format!(
                "not inside a git repository (no .git found above {})",
                cwd.display()
            ),
        )
    })?;
    let meshtree_dir = repo_root.join(MESHTREE_DIR);

    for sub in SUBDIRS {
        let dir = meshtree_dir.join(sub);
        fs::create_dir_all(&dir).map_err(|err| platform_error(&dir, &err))?;
    }

    let gitignore = write_if_absent(&meshtree_dir.join(".gitignore"), GITIGNORE)?;

    let config_path = meshtree_dir.join("config.toml");
    let config = write_if_absent(&config_path, Config::template())?;
    if config == FileOutcome::Kept {
        let text =
            fs::read_to_string(&config_path).map_err(|err| platform_error(&config_path, &err))?;
        Config::from_toml_str(&text).map_err(|err| {
            CliError::new(
                USAGE,
                format!("{err} (existing {} left unchanged)", config_path.display()),
            )
        })?;
    }

    Ok(InitReport {
        repo_root,
        config,
        gitignore,
    })
}

/// Creates `path` with `contents` unless it already exists. `create_new` makes
/// the existence check and the write one atomic step.
fn write_if_absent(path: &Path, contents: &str) -> Result<FileOutcome, CliError> {
    match fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(mut file) => {
            io::Write::write_all(&mut file, contents.as_bytes())
                .map_err(|err| platform_error(path, &err))?;
            Ok(FileOutcome::Created)
        }
        Err(err) if err.kind() == io::ErrorKind::AlreadyExists => Ok(FileOutcome::Kept),
        Err(err) => Err(platform_error(path, &err)),
    }
}

fn platform_error(path: &Path, err: &io::Error) -> CliError {
    CliError::new(PLATFORM, format!("{}: {err}", path.display()))
}
