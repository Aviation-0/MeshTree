const CONFIG: &str = r#"[project]
base_branch = "main"
integration_branch = "meshtree/integration"
validate = ["git --version"]
promote_validate = ["git --version"]
"#;

const INTEGRATION: &str = "meshtree/integration";

fn repo() -> TempDir {
    let repo = TempDir::repo_with_commit();
    assert_exit(&meshtree(repo.path(), &["init"]), 0);
    fs::write(repo.path().join(".meshtree/config.toml"), CONFIG).unwrap();
    repo
}

fn stdout(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

fn worktree(root: &Path, id: &str) -> PathBuf {
    root.join(".meshtree/worktrees").join(id)
}

/// Writes and commits `path` in a task worktree.
fn edit(wt: &Path, path: &str, body: &str) {
    let file = wt.join(path);
    fs::create_dir_all(file.parent().unwrap()).unwrap();
    fs::write(&file, body).unwrap();
    git(wt, &["add", path]);
    commit(wt, &format!("edit {path}"));
}

fn status(root: &Path, id: &str) -> String {
    let path = root.join(".meshtree/tasks").join(id).join("task.json");
    let task: Value = serde_json::from_str(&fs::read_to_string(path).unwrap()).unwrap();
    task["status"].as_str().unwrap().to_string()
}

/// The generated block of the root `AGENTS.md` (markers included).
fn agents_block(root: &Path) -> String {
    let text = fs::read_to_string(root.join("AGENTS.md")).unwrap();
    let begin = text
        .find("<!-- meshtree:active-sessions begin -->")
        .unwrap();
    let end_marker = "<!-- meshtree:active-sessions end -->";
    let end = text.find(end_marker).unwrap() + end_marker.len();
    text[begin..end].to_string()
}

fn show(root: &Path, path: &str) -> String {
    git(root, &["show", &format!("{INTEGRATION}:{path}")])
}

#[test]
fn full_lifecycle_spawn_claim_handoff_collect_merged() {
    let repo = repo();
    let root = repo.path();
    fs::write(root.join("AGENTS.md"), "# Contract\n\nBe nice.\n").unwrap();
    let daemon = DaemonProc::start(root);

    // spawn
    let out = meshtree(root, &["spawn", "auth-fix", "--agent", "vibe-cli"]);
    assert_exit(&out, 0);
    let id = stdout(&out)
        .lines()
        .find_map(|l| l.strip_prefix("task_id: "))
        .unwrap()
        .to_string();
    let wt = worktree(root, &id);
    assert_eq!(status(root, &id), "active");

    // claim (through the daemon)
    let out = meshtree(root, &["claim", &id, "src/auth/**"]);
    assert_exit(&out, 0);
    assert!(stdout(&out).contains("claimed src/auth/**"));

    // work
    edit(&wt, "src/auth/login.rs", "pub fn login() {}\n");

    // handoff: committed on the task branch, rendered into AGENTS.md
    let out = meshtree(
        root,
        &[
            "handoff",
            &id,
            "--set",
            "objective=Fix login",
            "--set",
            "state=ready to merge",
            "--set",
            "next=collect",
            "--set",
            "failing_tests=",
        ],
    );
    assert_exit(&out, 0);
    assert!(
        stdout(&out).contains("committed handoff"),
        "{}",
        stdout(&out)
    );
    let machine = {
        let task: Value = serde_json::from_str(
            &fs::read_to_string(root.join(".meshtree/tasks").join(&id).join("task.json")).unwrap(),
        )
        .unwrap();
        task["machine"].as_str().unwrap().to_string()
    };
    let before = format!(
        "<!-- meshtree:active-sessions begin -->\n\
         <!-- Generated by MeshTree. Do not edit between markers. -->\n\
         ## Active Sessions\n\
         - [{id}] auth-fix (vibe-cli, {machine}): ready to merge.\n  Next: collect.\n\
         <!-- meshtree:active-sessions end -->"
    );
    assert_eq!(agents_block(root), before);
    let agents = fs::read_to_string(root.join("AGENTS.md")).unwrap();
    assert!(agents.starts_with("# Contract\n\nBe nice.\n\n"), "{agents}");

    // collect → merged
    let out = meshtree(root, &["collect", &id]);
    assert_exit(&out, 0);
    assert!(stdout(&out).contains(&format!("merged {id} into {INTEGRATION}")));
    assert_eq!(status(root, &id), "merged");
    assert!(!wt.exists(), "worktree removed after merge");
    assert_eq!(show(root, "src/auth/login.rs"), "pub fn login() {}\n");
    let handoff = show(root, &format!(".meshtree/tasks/{id}/HANDOFF.md"));
    assert!(handoff.contains("**State:** ready to merge"), "{handoff}");

    // Claims were released at merge.
    let out = meshtree(root, &["sync"]);
    assert_exit(&out, 0);
    assert!(stdout(&out).contains("leases: 0"), "{}", stdout(&out));

    // AGENTS.md after the merge: no active sessions; the rest is untouched.
    let out = meshtree(root, &["render-agents"]);
    assert_exit(&out, 0);
    let after = "<!-- meshtree:active-sessions begin -->\n\
                 <!-- Generated by MeshTree. Do not edit between markers. -->\n\
                 ## Active Sessions\n\
                 - (none)\n\
                 <!-- meshtree:active-sessions end -->";
    assert_eq!(agents_block(root), after);
    assert_eq!(
        fs::read_to_string(root.join("AGENTS.md")).unwrap(),
        format!("# Contract\n\nBe nice.\n\n{after}\n")
    );

    // promote: main fast-forwards to the validated integration tip.
    assert_exit(&meshtree(root, &["promote"]), 0);
    assert_eq!(
        git(root, &["rev-parse", "main"]),
        git(root, &["rev-parse", INTEGRATION])
    );
    daemon.stop(root);
}

/// A minimal MCP stdio client (`meshtree mcp`).
struct Mcp {
    child: Child,
    stdin: Option<ChildStdin>,
    stdout: BufReader<ChildStdout>,
    next_id: u64,
}

impl Mcp {
    fn start(cwd: &Path) -> Self {
        let mut child = Command::new(env!("CARGO_BIN_EXE_meshtree"))
            .arg("mcp")
            .current_dir(cwd)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()
            .expect("spawn meshtree mcp");
        let stdin = child.stdin.take();
        let stdout = BufReader::new(child.stdout.take().unwrap());
        let mut mcp = Self {
            child,
            stdin,
            stdout,
            next_id: 0,
        };
        let init = mcp.request(
            "initialize",
            json!({ "protocolVersion": "2025-06-18", "capabilities": {},
                    "clientInfo": { "name": "e2e", "version": "0" } }),
        );
        assert_eq!(init["result"]["serverInfo"]["name"], "meshtree");
        let note = json!({ "jsonrpc": "2.0", "method": "notifications/initialized" });
        let stdin = mcp.stdin.as_mut().unwrap();
        writeln!(stdin, "{note}").unwrap();
        mcp
    }

    fn request(&mut self, method: &str, params: Value) -> Value {
        self.next_id += 1;
        let message =
            json!({ "jsonrpc": "2.0", "id": self.next_id, "method": method, "params": params });
        let stdin = self.stdin.as_mut().unwrap();
        writeln!(stdin, "{message}").unwrap();
        stdin.flush().unwrap();
        let mut line = String::new();
        self.stdout.read_line(&mut line).unwrap();
        serde_json::from_str(&line).unwrap_or_else(|e| panic!("{e}: {line:?}"))
    }

    /// `tools/call` → `Ok(structuredContent)` or `Err(error code)`.
    fn call(&mut self, tool: &str, arguments: Value) -> Result<Value, String> {
        let reply = self.request(
            "tools/call",
            json!({ "name": tool, "arguments": arguments }),
        );
        let result = &reply["result"];
        let content = result["structuredContent"].clone();
        if result["isError"] == true {
            Err(content["code"].as_str().unwrap_or_default().to_string())
        } else {
            Ok(content)
        }
    }
}

impl Drop for Mcp {
    fn drop(&mut self) {
        drop(self.stdin.take());
        let _ = self.child.wait();
    }
}

#[test]
fn two_agents_mcp_and_cli_parallel_session_zero_overwrites() {
    let repo = repo();
    let root = repo.path();
    let daemon = DaemonProc::start(root);
    let barrier = Barrier::new(2);

    // Two agents in parallel: "ide" over MCP, "term" over the CLI. Each
    // spawns its own task and claims its own area, then both race for the
    // same shared file.
    let (ide, term) = std::thread::scope(|s| {
        let ide = s.spawn(|| {
            let mut mcp = Mcp::start(root);
            let task = mcp
                .call(
                    "spawn_task",
                    json!({ "name": "ide-ui", "agent": "antigravity", "claims": ["ui/**"] }),
                )
                .expect("spawn over MCP");
            let id = task["task_id"].as_str().unwrap().to_string();
            barrier.wait();
            let shared = mcp.call(
                "claim_paths",
                json!({ "task_id": id, "paths": ["shared/config.rs"] }),
            );
            let won = match shared {
                Ok(_) => true,
                Err(code) => {
                    assert_eq!(code, "MT-001");
                    false
                }
            };
            (id, won)
        });
        let term = s.spawn(|| {
            let out = meshtree(
                root,
                &[
                    "spawn", "term-api", "--agent", "vibe-cli", "--claim", "api/**",
                ],
            );
            assert_exit(&out, 0);
            let id = stdout(&out)
                .lines()
                .find_map(|l| l.strip_prefix("task_id: "))
                .unwrap()
                .to_string();
            barrier.wait();
            let out = meshtree(root, &["claim", &id, "shared/config.rs"]);
            let won = match out.status.code() {
                Some(0) => true,
                Some(20) => {
                    assert!(stderr(&out).contains("MT-001"), "{}", stderr(&out));
                    false
                }
                other => panic!("claim exit {other:?}: {}", stderr(&out)),
            };
            (id, won)
        });
        (ide.join().unwrap(), term.join().unwrap())
    });
    let ((ide_id, ide_won), (term_id, term_won)) = (ide, term);
    assert!(
        ide_won ^ term_won,
        "exactly one agent holds the shared file (ide {ide_won}, term {term_won})"
    );

    // Both agents work in parallel in their own worktrees; both also touch
    // the shared file, the loser without a claim (a misbehaving agent).
    let (winner, loser) = if ide_won {
        (&ide_id, &term_id)
    } else {
        (&term_id, &ide_id)
    };
    std::thread::scope(|s| {
        s.spawn(|| {
            let wt = worktree(root, &ide_id);
            edit(&wt, "ui/view.rs", "ide view\n");
            edit(&wt, "shared/config.rs", &format!("by {ide_id}\n"));
        });
        s.spawn(|| {
            let wt = worktree(root, &term_id);
            edit(&wt, "api/route.rs", "term route\n");
            edit(&wt, "shared/config.rs", &format!("by {term_id}\n"));
        });
    });

    // The loser collects first while the winner still holds the claim: the
    // merge gate refuses it (MT-032) instead of overwriting.
    let out = meshtree(root, &["collect", loser]);
    assert_exit(&out, 20);
    assert!(stderr(&out).contains("MT-032"), "{}", stderr(&out));
    assert!(stderr(&out).contains(winner.as_str()), "{}", stderr(&out));
    assert_eq!(status(root, loser), "failed");

    // The winner collects (over MCP if it is the IDE agent, else the CLI).
    if ide_won {
        let mut mcp = Mcp::start(root);
        let merged = mcp
            .call("collect_task", json!({ "task_id": winner }))
            .expect("collect over MCP");
        assert_eq!(merged["status"], "merged");
    } else {
        assert_exit(&meshtree(root, &["collect", winner]), 0);
    }
    assert_eq!(status(root, winner), "merged");

    // Zero overwrites: the shared file holds the claim holder's bytes, and
    // the winner's own work is intact on the integration branch.
    assert_eq!(show(root, "shared/config.rs"), format!("by {winner}\n"));
    let (own, body) = if ide_won {
        ("ui/view.rs", "ide view\n")
    } else {
        ("api/route.rs", "term route\n")
    };
    assert_eq!(show(root, own), body);

    // The loser's work is not lost either: its branch still has every edit,
    // ready to be re-spawned on top of integration.
    let loser_branch = format!("meshtree/{loser}");
    let (loser_own, loser_body) = if ide_won {
        ("api/route.rs", "term route\n")
    } else {
        ("ui/view.rs", "ide view\n")
    };
    assert_eq!(
        git(root, &["show", &format!("{loser_branch}:{loser_own}")]),
        loser_body
    );
    assert_eq!(
        git(root, &["show", &format!("{loser_branch}:shared/config.rs")]),
        format!("by {loser}\n")
    );
    daemon.stop(root);
}
